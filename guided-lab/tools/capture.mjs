#!/usr/bin/env node
/*
 * Record a reference system by running the workshop's workloads against a local Ollama server.
 * Same lab/core.js and lab/workloads.js as the browser lab. Node 18+, no packages.
 *
 *   node tools/capture.mjs --id sys-mine --name "My laptop" [--base http://127.0.0.1:11434]
 *        [--model qwen2.5:1.5b] [--n 100] [--num-gpu 0] [--note "how the server was started"]
 */
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
require(path.join(here, '..', 'lab', 'core.js'));
const Core = require(path.join(here, '..', 'lab', 'workloads.js'));
const args = {};
for (let i = 2; i < process.argv.length; i += 2) args[process.argv[i].replace(/^--/, '')] = process.argv[i + 1];
if (!args.id) { console.error('usage: node tools/capture.mjs --id <system-id> --name "<name>" [options]  (see file header)'); process.exit(2); }
const cfg = { base: args.base || Core.DEFAULT_BASE, model: args.model || Core.DEFAULT_MODEL, extraOptions: args['num-gpu'] != null ? { num_gpu: Number(args['num-gpu']) } : {} };
const n = Number(args.n || Core.SAMPLE.standard);
const outDir = path.resolve(args.out || path.join(here, '..', 'lab', 'data', 'recorded'));
const sh = (cmd, a) => { try { return execFileSync(cmd, a, { encoding: 'utf8' }).trim(); } catch { return null; } };

const model = (await Core.listModels(cfg)).find((m) => m.name === cfg.model);
if (!model) { console.error('Model ' + cfg.model + ' is not installed on ' + cfg.base); process.exit(1); }
const observed = await Core.observeSystem(cfg);
const batt = sh('pmset', ['-g', 'batt']);
const profile = {
  id: args.id, name: args.name || args.id, kind: 'recorded', captured_at: new Date().toISOString(),
  captured_with: 'tools/capture.mjs (core ' + Core.CORE_VERSION + '), Node ' + process.version,
  command: 'node tools/capture.mjs ' + process.argv.slice(2).map((a) => (/\s/.test(a) ? JSON.stringify(a) : a)).join(' '),
  hardware: {
    machine: sh('sysctl', ['-n', 'hw.model']) || os.machine(), chip: sh('sysctl', ['-n', 'machdep.cpu.brand_string']) || (os.cpus()[0] || {}).model || 'unknown',
    cpu_cores: os.cpus().length, ram_gb: Math.round(os.totalmem() / 2 ** 30),
    os: os.platform() === 'darwin' ? 'macOS ' + (sh('sw_vers', ['-productVersion']) || os.release()) : os.platform() + ' ' + os.release(),
    power: batt ? (/AC Power/.test(batt) ? 'AC power' : 'battery') : 'unknown', load_average_at_start: os.loadavg().map((x) => Math.round(x * 100) / 100),
  },
  server: { note: args.note || '' }, observed,
  model: { name: model.name, digest: model.digest, size_bytes: model.size, details: model.details },
  request_options: Object.assign({}, Core.BASE_OPTIONS, cfg.extraOptions), n, runs: { done: [], load: [], mixed: [] },
};
const plan = [['done', Core.DEFAULTS.done], ['load', { users: 1 }], ['load', { users: 4 }], ['mixed', { workers: 1, share: false, json: false }], ['mixed', { workers: 4, share: true, json: false }]];
for (const [name, settings] of plan) {
  process.stdout.write('[' + args.id + '] ' + name + ' ' + JSON.stringify(settings) + ' ');
  const t0 = Date.now();
  let last = 0;
  const result = await Core.experiments[name](cfg, { n, settings, onStep: ({ i }) => { if (i - last >= 20) { last = i; process.stdout.write('.'); } } });
  profile.runs[name].push({ id: args.id + '-' + name + '-' + profile.runs[name].length, at: new Date().toISOString(), settings: result.settings, n, wall_ms: Date.now() - t0, result });
  console.log(' ' + result.records.length + ' requests in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
}
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, args.id + '.json'), JSON.stringify(profile));
const all = fs.readdirSync(outDir).filter((f) => f.endsWith('.json')).map((f) => JSON.parse(fs.readFileSync(path.join(outDir, f), 'utf8'))).sort((a, b) => a.id.localeCompare(b.id));
fs.writeFileSync(path.join(outDir, '..', 'recorded.js'), '/* Generated by tools/capture.mjs from lab/data/recorded/*.json. Recorded runs, not live data. */\nwindow.RECORDED_PROFILES = ' + JSON.stringify(all) + ';\n');
console.log('wrote ' + args.id + '.json and rebuilt recorded.js (' + all.length + ' system(s))');
